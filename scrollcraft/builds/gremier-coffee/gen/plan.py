lines = open('BLUEPRINT.md', encoding='utf8').read().split('\n')
out, missing = [], []
i = 0
while i < len(lines):
    m = re.match(r'- \[( |x)\] (R[0-9a-z]+\.[0-9]+) ', lines[i])
    if m:
        rid = m.group(2)
        plan = PLAN.get(rid)
        old = lines[i + 1] if i + 1 < len(lines) and lines[i + 1].strip().startswith('plan:') else ''
        if plan:
            out.append(lines[i].replace('- [ ]', '- [x]', 1))
            out.append('  plan: ' + plan)
        else:
            missing.append(rid)
            out.append(lines[i])
            if old:
                out.append(old)
        i += 2 if old else 1
        continue
    out.append(lines[i])
    i += 1
open('BLUEPRINT.md', 'w', encoding='utf8').write('\n'.join(out))
print('missing', missing)
