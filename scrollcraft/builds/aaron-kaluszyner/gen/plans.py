path = 'scrollcraft/builds/aaron-kaluszyner/BLUEPRINT.md'
lines = open(path, encoding='utf8').read().split('\n')
out, cur, missing = [], None, []
for ln in lines:
    m = re.match(r'^- \[[ x]\] (R[0-9][0-9a-z]*\.[0-9]+) ', ln)
    if m:
        cur = m.group(1)
        if cur not in P: missing.append(cur)
        done = cur in P and not P[cur].startswith('n/a')
        ln = ('- [x] ' if done else '- [ ] ') + ln[6:]
    elif cur and ln.startswith('  plan:'):
        ln = '  plan: ' + P.get(cur, ln[8:])
        cur = None
    out.append(ln)
open(path, 'w', encoding='utf8').write('\n'.join(out))
extra = set(P) - {re.match(r'^- \[[ x]\] (\S+)', l).group(1) for l in out if re.match(r'^- \[[ x]\] R', l)}
print('missing:', missing, 'unknown:', sorted(extra))
