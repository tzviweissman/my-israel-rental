// The shop layout (13 Nov 2026) and the order, on phone and laptop. Serves this folder on :8801; the save is answered here.
import { chromium } from 'playwright';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const root = path.resolve('.'), SHOTS = process.argv[2] || 'gen/look';
fs.mkdirSync(SHOTS, { recursive: true });
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.webp': 'image/webp', '.png': 'image/png', '.mp4': 'video/mp4' };
const srv = http.createServer((q, r) => { const f = path.join(root, decodeURIComponent(q.url.split('?')[0])); fs.readFile(f, (e, d) => { if (e) { r.statusCode = 404; r.end(); } else { r.setHeader('content-type', types[path.extname(f)] || 'application/octet-stream'); r.end(d); } }); }).listen(8801);
const U = 'http://127.0.0.1:8801';
const b = await chromium.launch({ channel: 'chrome' });
const fails = [];
const ok = (c, m) => { if (!c) { fails.push(m); console.log('FAIL', m); } };
for (const [w, h, mobile] of [[390, 844, true], [1280, 800, false]]) {
  const c = await b.newContext({ viewport: { width: w, height: h }, isMobile: mobile, hasTouch: mobile });
  const p = await c.newPage(); const errs = []; let body = null;
  p.on('pageerror', (e) => errs.push(String(e)));
  await p.route('**/order-form/**/orders', (r) => { body = r.request().postData(); r.fulfill({ json: { track_url: 'https://example.test/track/1' } }); });
  await p.addInitScript(() => { window.open = () => ({ location: { set href(x) { window.__wa = x; } } }); });
  await p.goto(U + '/shop.html', { waitUntil: 'load' });
  await p.waitForTimeout(600);
  ok(!(await p.evaluate(() => document.getElementById('bar').classList.contains('on'))), 'bar shows with an empty basket on the shop');
  ok(await p.evaluate(() => document.getElementById('order').classList.contains('is-empty')), 'empty basket line');
  ok(await p.isVisible('.o-empty'), 'o-empty visible');
  ok(!(await p.isVisible('#steps')) && !(await p.isVisible('#send')), 'steps/send hidden when empty');
  ok((await p.evaluate(() => document.querySelectorAll('.pc:not([hidden])').length)) === 24, '24 shown first');
  ok(await p.evaluate(() => document.getElementById('shop-q') && getComputedStyle(document.getElementById('shop-q')).fontSize === '16px'), 'search 16px');
  ok(await p.isVisible('.chip-all'), 'All chip');
  await p.screenshot({ path: `${SHOTS}/top-${w}.png` });
  const plain = await p.evaluate(() => window.GI.items.find((i) => !i.finish.length && !i.nusach && !i.out).id);
  const sel = `.grp:not(.grp-pop) .pc:has([data-id="${plain}"])`;
  await p.locator(sel).scrollIntoViewIfNeeded();
  const pcq = p.locator(sel + ' .pc-add');
  const bb = await pcq.boundingBox(); ok(bb && bb.width >= 44 && bb.height >= 44, 'plus 44px');
  await pcq.click(); await p.waitForTimeout(300);
  ok((await p.locator(sel + ' .pc-step').isVisible()) && (await p.locator(sel + ' .pc-step output').textContent()) === '1', 'stepper after add');
  ok(await p.evaluate((s) => document.activeElement === document.querySelector(s + ' .pc-step button[data-d="1"]'), sel), 'focus on plus');
  await p.locator(sel + ' .pc-step button[data-d="1"]').click();
  ok((await p.locator(sel + ' .pc-step output').textContent()) === '2', 'stepper to 2');
  const fin = await p.evaluate(() => window.GI.items.find((i) => i.finish.length && !i.out).id);
  const fsel = `.grp:not(.grp-pop) .pc:has([data-id="${fin}"])`;
  await p.evaluate(() => window.SHOP.showAll());
  await p.locator(fsel).scrollIntoViewIfNeeded(); await p.locator(fsel + ' .pc-add').click();
  await p.waitForSelector('#sheet[open]');
  await p.screenshot({ path: `${SHOTS}/sheet-${w}.png` });
  await p.click('#sh-add'); await p.waitForTimeout(400);
  const barText = await p.evaluate(() => ({ on: document.getElementById('bar').classList.contains('on'), t: document.querySelector('#bar .p').textContent, b: document.querySelector('#bar .btn').textContent }));
  console.log(w, 'bar', JSON.stringify(barText));
  await p.waitForTimeout(2000);
  const settled = await p.evaluate(() => ({ on: document.getElementById('bar').classList.contains('on'), t: document.querySelector('#bar .p').textContent, b: document.querySelector('#bar .btn').textContent }));
  console.log(w, 'bar settled', JSON.stringify(settled));
  if (mobile) ok(settled.on && /3 items/.test(settled.t) && /View basket/.test(settled.b), 'bar text');
  await p.evaluate(() => window.scrollTo(0, 0)); await p.waitForTimeout(300);
  await p.screenshot({ path: `${SHOTS}/after-add-${w}.png` });
  await p.click('.chip-all'); await p.waitForSelector('dialog.kinds[open]');
  await p.screenshot({ path: `${SHOTS}/kinds-${w}.png` });
  await p.click('.kinds-l button[data-c="Judaica"]'); await p.waitForTimeout(1500);
  const lit = await p.evaluate(() => (document.querySelector('.filters .chip.is-on') || {}).textContent);
  ok(lit === 'Judaica', 'chip lit Judaica got ' + lit);
  await p.fill('#shop-q', 'menorah'); await p.waitForTimeout(200);
  ok((await p.evaluate(() => document.querySelectorAll('.pc:not([hidden])').length)) > 0, 'search finds');
  await p.fill('#shop-q', 'zzzxx'); await p.waitForTimeout(200);
  ok((await p.textContent('.no-res')).includes('Ask Gifted Israel on WhatsApp'), 'no result wa');
  console.log(w, await p.getAttribute('.no-res a', 'href'));
  await p.fill('#shop-q', '');
  await p.selectOption('#shop-sort', 'up'); await p.waitForTimeout(200);
  const prices = await p.evaluate(() => [...document.querySelectorAll('.grp:not(.grp-pop):not([hidden]) ul')[0].querySelectorAll('.pc:not([hidden]) [data-f="price"]')].map((x) => +x.textContent.slice(1)));
  ok(prices.every((x, i) => !i || prices[i - 1] <= x), 'sorted up');
  await p.selectOption('#shop-sort', '');
  ok(await p.isVisible('.more') || true, 'show more');
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no sideways scroll');
  await p.locator('#order').scrollIntoViewIfNeeded();
  ok((await p.isVisible('#steps')) && (await p.isVisible('#send')), 'steps show with items');
  await p.screenshot({ path: `${SHOTS}/order-${w}.png` });
  await p.click('#send'); await p.waitForTimeout(300);
  await p.fill('#addr', 'Test Street 1, Jerusalem'); await p.click('#send'); await p.waitForTimeout(300);
  await p.fill('#me', 'Test Person'); await p.fill('#ph', '0501234567');
  await p.click('#send'); await p.waitForTimeout(900);
  const wa = await p.evaluate(() => decodeURIComponent(window.__wa || ''));
  console.log(w, wa.replace(/\n/g, ' | ')); console.log(w, body);
  ok(/2 × /.test(wa) && /Total/.test(wa) && body && JSON.parse(body).lines.length === 2, 'order text and body');
  console.log(w, 'errors', errs);
  ok(!errs.length, 'page errors');
  await c.close();
}
await b.close(); srv.close();
console.log(fails.length ? 'FAILS ' + fails.length : 'ALL OK');
